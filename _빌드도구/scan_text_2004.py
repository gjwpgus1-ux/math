def main():
    path = sys.argv[1]
    D = json.load(open(path, encoding='utf-8'))
    n = 0
    for e in D['exams']:
        raw = e.get('raw', e.get('name', ''))
        src = GA if raw == '2004가' else (NA if raw == '2004나' else None)
        if src is None:
            continue
        for q in e['questions']:
            if q['num'] in src:
                q['text'] = src[q['num']]
                n += 1
    json.dump(D, open(path, 'w', encoding='utf-8'), ensure_ascii=False)
    print('%d문항 텍스트 반영' % n)


if __name__ == '__main__':
    main()
