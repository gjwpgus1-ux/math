    D = json.load(open(path, encoding='utf-8'))
    n = 0
    for e in D['exams']:
        src = GA if '가형' in e['name'] else (NA if '나형' in e['name'] else None)
        if src is None:
            continue
        for q in e['questions']:
            if q['num'] in src:
                q['text'] = src[q['num']]
                n += 1
    json.dump(D, open(path, 'w', encoding='utf-8'), ensure_ascii=False)
